import test from 'node:test';
import assert from 'node:assert/strict';
import { check, rulesFor, runSelfTest, rules } from '../../packages/core/index.mjs';

const OVERLAY_B = ['perfect-tense', 'progressive-tense', 'passive-in-procedure', 'modal-should', 'modal-may'];
const found = (text, ruleId, profile = 'strict-plain') =>
  check(text, { profile }).issues.filter(i => i.ruleId === ruleId);

test('overlay B rules exist only in strict-plain', () => {
  const base = rulesFor('base').map(r => r.id);
  const strict = rulesFor('strict-plain').map(r => r.id);
  for (const id of OVERLAY_B) {
    assert.ok(!base.includes(id), `${id} not in base`);
    assert.ok(strict.includes(id), `${id} in strict-plain`);
  }
});

test("'should' is an error and 'may' a warning under strict-plain; neither under base", () => {
  const text = 'You should rotate your keys. The sync may take a few minutes.';
  const should = found(text, 'modal-should');
  const may = found(text, 'modal-may');
  assert.deepEqual(should.map(i => [i.text, i.severity]), [['should', 'error']]);
  assert.deepEqual(may.map(i => [i.text, i.severity]), [['may', 'warning']]);
  const base = check(text, { profile: 'base' }).issues.map(i => i.ruleId);
  assert.ok(!base.includes('modal-should') && !base.includes('modal-may'));
});

test("'May' as a month is not flagged; 'May' at the start of a sentence is", () => {
  assert.deepEqual(found('Version 2.4 shipped in May 2026. The next one is due in May.', 'modal-may'), []);
  assert.deepEqual(found('Done. May cause a short delay.', 'modal-may').map(i => i.text), ['May']);
});

test('perfect forms are flagged, with modal hedges and possession left alone', () => {
  assert.deepEqual(found('The team has fixed the crash.', 'perfect-tense').map(i => i.text), ['has fixed']);
  assert.deepEqual(found('Demo Sync has been used since 2023.', 'perfect-tense').map(i => i.text), ['has been']);
  for (const ok of ['The sync may have failed.', 'It must have changed overnight.', 'You have to restart the service.',
    'Each user has read access.', 'The project has a set of tags.', 'You need the Owner role.']) {
    assert.deepEqual(found(ok, 'perfect-tense'), [], ok);
  }
});

test('progressive forms are flagged, with -ing adjectives and nouns left alone', () => {
  assert.deepEqual(found('The service is running.', 'progressive-tense').map(i => i.text), ['is running']);
  assert.deepEqual(found('The files were being copied.', 'progressive-tense').map(i => i.text), ['were being']);
  for (const ok of ['Two files are missing.', 'The following steps apply.', 'There is nothing to sync.', 'The upload is pending.']) {
    assert.deepEqual(found(ok, 'progressive-tense'), [], ok);
  }
});

test('passive voice is flagged in instructions and procedures only', () => {
  assert.deepEqual(found('1. The access key is entered in the Key field.', 'passive-in-procedure').map(i => i.text), ['is entered']);
  // Owner decision after the 2.5 precision gate: main clauses only, and only the first sentence of a numbered step.
  assert.deepEqual(found('Restart the service after the files are copied.', 'passive-in-procedure'), []);
  assert.deepEqual(found('1. Run `demosync migrate`. The migration is performed in place.', 'passive-in-procedure'), []);
  assert.deepEqual(found('Make sure that the old cache is deleted.', 'passive-in-procedure').map(i => i.text), ['is deleted']);
  assert.deepEqual(found('1. The new version must be installed over the old one.', 'passive-in-procedure').map(i => i.text), ['must be installed']);
  // A description, a state ("is installed") and a named actor ("by") are left alone.
  assert.deepEqual(found('The changes are written to the server every hour.', 'passive-in-procedure'), []);
  assert.deepEqual(found('1. Make sure that the agent is installed.', 'passive-in-procedure'), []);
  assert.deepEqual(found('Select Export. The report is generated by the scheduler.', 'passive-in-procedure'), []);
});

test('timing: the self-test on every rule stays under 500 ms for 10,000 words', () => {
  const r = runSelfTest(rules);
  assert.ok(r.timing.words >= 10000);
  assert.ok(r.timing.ok, `${r.timing.ms} ms`);
});
